/** Generate the notices shipped with Lectern from installed production packages. */
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'

const ROOT = resolve(import.meta.dirname, '..')
const OUTPUT = join(ROOT, 'resources', 'THIRD_PARTY_NOTICES.txt')
const rootPackage = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'))
const licenseName = /^(?:licen[cs]e|copying|notice)(?:[._-].*)?$/i

function packageDirectory(name, fromDirectory) {
  let directory = fromDirectory
  while (true) {
    const candidate = join(directory, 'node_modules', name)
    if (existsSync(join(candidate, 'package.json'))) return candidate
    const parent = dirname(directory)
    if (parent === directory) return null
    directory = parent
  }
}

function readPackage(directory) {
  return JSON.parse(readFileSync(join(directory, 'package.json'), 'utf8'))
}

function licenseFiles(directory) {
  return readdirSync(directory, { withFileTypes: true })
    .filter((entry) => entry.isFile() && licenseName.test(entry.name))
    .map((entry) => ({
      name: entry.name,
      text: readFileSync(join(directory, entry.name), 'utf8').trim()
    }))
    .sort((a, b) => a.name.localeCompare(b.name))
}

function installedProductionPackages() {
  const found = new Map()

  function visit(name, fromDirectory, optional = false) {
    const directory = packageDirectory(name, fromDirectory)
    if (!directory) {
      if (optional) return
      throw new Error(`Production dependency ${name} is not installed`)
    }

    const packageJson = readPackage(directory)
    const key = `${packageJson.name ?? name}@${packageJson.version ?? 'unknown'}`
    if (found.has(key)) return
    found.set(key, { directory, packageJson })

    for (const dependency of Object.keys(packageJson.dependencies ?? {})) {
      visit(dependency, directory)
    }
    for (const dependency of Object.keys(packageJson.optionalDependencies ?? {})) {
      visit(dependency, directory, true)
    }
    for (const dependency of Object.keys(packageJson.peerDependencies ?? {})) {
      const peerOptional = packageJson.peerDependenciesMeta?.[dependency]?.optional === true
      visit(dependency, directory, peerOptional)
    }
  }

  for (const dependency of Object.keys(rootPackage.dependencies ?? {})) visit(dependency, ROOT)
  return [...found.values()].sort((a, b) => {
    const aKey = `${a.packageJson.name}@${a.packageJson.version}`
    const bKey = `${b.packageJson.name}@${b.packageJson.version}`
    return aKey.localeCompare(bKey)
  })
}

function renderEntry(title, declaredLicense, files) {
  const parts = [title, `Declared license: ${declaredLicense || 'Unknown'}`]
  if (files.length === 0) {
    parts.push('License text: Unknown (no license file was included with this installed asset).')
  } else {
    for (const file of files) parts.push(`--- ${file.name} ---\n${file.text}`)
  }
  return parts.join('\n\n')
}

function packageEntry({ directory, packageJson }) {
  const declared = typeof packageJson.license === 'string' ? packageJson.license : 'Unknown'
  return renderEntry(
    `${packageJson.name ?? 'Unknown package'} ${packageJson.version ?? 'unknown version'}`,
    declared,
    licenseFiles(directory)
  )
}

function namedFile(label, path) {
  return { name: label, text: readFileSync(path, 'utf8').trim() }
}

const publicRoot = join(ROOT, 'src', 'renderer', 'public')
const vendored = [
  renderEntry('Vendored renderer asset: MathJax', 'Apache-2.0', [
    namedFile('mathjax/LICENSE', join(ROOT, 'node_modules', 'mathjax', 'LICENSE'))
  ]),
  renderEntry(
    'Vendored renderer asset: PDF.js and bundled PDF resources',
    'Apache-2.0 and component licenses below',
    [
      namedFile('pdfjs-dist/LICENSE', join(ROOT, 'node_modules', 'pdfjs-dist', 'LICENSE')),
      ...[
        'cmaps/LICENSE',
        'iccs/LICENSE',
        'standard_fonts/LICENSE_FOXIT',
        'standard_fonts/LICENSE_LIBERATION',
        'wasm/LICENSE_JBIG2',
        'wasm/LICENSE_OPENJPEG',
        'wasm/LICENSE_PDFJS_JBIG2',
        'wasm/LICENSE_PDFJS_OPENJPEG',
        'wasm/LICENSE_PDFJS_QCMS',
        'wasm/LICENSE_QCMS'
      ].map((path) => namedFile(`public/${path}`, join(publicRoot, path)))
    ]
  ),
  renderEntry('Vendored renderer asset: Tesseract.js worker and core', 'Apache-2.0', [
    namedFile('tesseract.js/LICENSE.md', join(ROOT, 'node_modules', 'tesseract.js', 'LICENSE.md')),
    namedFile('tesseract.js-core/LICENSE', join(ROOT, 'node_modules', 'tesseract.js-core', 'LICENSE'))
  ]),
  renderEntry('Vendored renderer asset: Tesseract English language data', 'Unknown', [])
]

const header = [
  'LECTERN THIRD-PARTY NOTICES',
  '',
  'Generated by `npm run notices`; do not edit by hand.',
  'A missing license file is reported as Unknown rather than inferred.',
  '',
  'PRODUCTION DEPENDENCIES',
  '======================='
].join('\n')

const body = installedProductionPackages().map(packageEntry)
const document = [
  header,
  ...body,
  'VENDORED RENDERER ASSETS\n========================',
  ...vendored
].join('\n\n' + '-'.repeat(78) + '\n\n')

writeFileSync(OUTPUT, `${document}\n`, 'utf8')
console.log(`wrote ${OUTPUT} (${body.length} production packages, ${vendored.length} asset groups)`)
